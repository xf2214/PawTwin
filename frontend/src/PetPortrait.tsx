export function PetPortrait({ pet, className, decorative = true }: { pet: PetKind; className?: string; decorative?: boolean }) {
  const { name, species } = PET_PROFILES[pet]
  return <svg
    viewBox="0 0 128 144"
    className={className}
    aria-hidden={decorative ? true : undefined}
    role={decorative ? undefined : 'img'}
    aria-label={decorative ? undefined : t(`${name} · ${species}角色示意`, `${name} · ${t(species)} character preview`)}
  ><PetArtwork pet={pet} /></svg>
}
